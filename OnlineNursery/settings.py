# RENDER BACKUP SYSTEM
# ============================================================

if 'RENDER' in os.environ:

    try:

        db_path = BASE_DIR / 'db.sqlite3'

        if not os.path.exists(db_path):

            logger.info(
                "db.sqlite3 not found, restoring from backup..."
            )

            execute_from_command_line(
                ['manage.py', 'restore_db']
            )

        else:

            logger.info(
                "db.sqlite3 exists, skipping restore from backup."
            )

        backup_thread = threading.Thread(
            target=backup_database,
            daemon=True
        )

        backup_thread.start()

        print("Backup thread started")

    except Exception as e:

        print(
            f"Error starting backup system: {str(e)}"
        )
